# Import necessary machine learning models and evaluation metrics
from sklearn.svm import LinearSVC, SVC
from sklearn.metrics import classification_report, accuracy_score, confusion_matrix
from sklearn.preprocessing import StandardScaler  # Added to make code standalone

# Import data manipulation and visualization libraries
from matplotlib import pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from keras.datasets import mnist  # Added to fetch the MNIST dataset

# -------------------------------------------------------------------------
# 1. DATA LOADING & PREPROCESSING
# -------------------------------------------------------------------------

# Load the MNIST handwritten digit dataset split into training and testing sets
(X_train, y_train), (X_test, y_test) = mnist.load_data()

# Print the original dimensions of the dataset (expected: 28x28 images)
print("Original Training Shape:", X_train.shape)
print("Original Testing Shape:", X_test.shape)

# Flatten the 2D images (28x28) into a 1D vector (784 features) and convert to float32
X_train = X_train.reshape(-1, 28 * 28).astype(np.float32)
X_test = X_test.reshape(-1, 28 * 28).astype(np.float32)

# Print the reshaped dimensions to confirm flattening
print("Reshaped Training Shape:", X_train.shape)
print("Reshaped Testing Shape:", X_test.shape)

# Standardize features by removing the mean and scaling to unit variance
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# -------------------------------------------------------------------------
# 2. DATA VISUALIZATION (TRAINING SAMPLES)
# -------------------------------------------------------------------------

# Create a grid plot (2 rows, 5 columns) to display the first 10 training images
fig, axes = plt.subplots(2, 5, figsize=(10, 5))
for i, ax in enumerate(axes.ravel()):
    # Reshape the flattened 1D array back to 28x28 for image display
    ax.imshow(X_train[i].reshape(28, 28), cmap='gray')
    ax.set_title(f"Label: {y_train[i]}")
    ax.axis('off')  # Hide axes borders and ticks
plt.tight_layout()
plt.show()

# -------------------------------------------------------------------------
# 3. MODEL TRAINING & PREDICTION
# -------------------------------------------------------------------------

# Initialize a Linear Support Vector Classifier
# dual=False solves the primal optimization problem (preferred when samples > features)
clf = LinearSVC(dual=False, max_iter=10)

# Train the classifier using the scaled training data
clf.fit(X_train_scaled, y_train)

# Generate predictions on the scaled test dataset
y_pred = clf.predict(X_test_scaled)

# -------------------------------------------------------------------------
# 4. METRICS & PERFORMANCE EVALUATION
# -------------------------------------------------------------------------

# Calculate and print overall accuracy score
print("Accuracy:", accuracy_score(y_test, y_pred))

# Generate and print a comprehensive text report of precision, recall, and F1-score
print(classification_report(y_test, y_pred))

# Compute the confusion matrix to evaluate classification errors per digit class
cm = confusion_matrix(y_test, y_pred)
plt.figure(figsize=(10, 8))
# Plot the confusion matrix as a heatmap using Seaborn
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=np.unique(y_test), yticklabels=np.unique(y_test))
plt.xlabel('Predicted Label')
plt.ylabel('True Label')
plt.title('Confusion Matrix')
plt.show()

# -------------------------------------------------------------------------
# 5. VISUALIZING TEST PREDICTIONS
# -------------------------------------------------------------------------

# Plot the first 10 test images along with their ground truth and predicted labels
fig, axes = plt.subplots(2, 5, figsize=(10, 5))
for i, ax in enumerate(axes.ravel()):
    ax.imshow(X_test[i].reshape(28, 28), cmap='gray')
    ax.set_title(f"Label: {y_test[i]} Predicted {y_pred[i]}")
    ax.axis('off')
plt.tight_layout()
plt.show()

# Find the indices of all test samples that the model classified incorrectly
misclassified_indices = np.where(y_test != y_pred)[0]

# Plot the first 10 misclassified images to analyze model weaknesses
plt.figure(figsize=(15, 5))
for i, index in enumerate(misclassified_indices[:10]):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_test[index].reshape(28, 28), cmap='gray')
    plt.title(f"True: {y_test[index]}\nPred: {y_pred[index]}")
    plt.axis('off')
plt.tight_layout()
plt.show()

weights = clf.coef_
print(weights.shape)

biases = clf.intercept_
print(biases.shape)

# --- Export SVM model (int8 weights + float scale/bias) -------------------
# Changes for the VSDSquadron PRO (FE310, 16 KB RAM):
#  * all tables are `const` so they live in flash (.rodata), not RAM (.data)
#  * weight_scale is exported so the C code can de-quantize the weights
#  * bias is `float` (rv32imac has no FPU; double would be slower soft-float)
max_val = np.abs(weights).max()
weight_scale = max_val / 127.0
weights_int8 = np.clip(np.round(weights / weight_scale), -127, 127).astype(np.int8)
with open("svm_model_mnist_8b.h", "w") as f:
    f.write("#ifndef SVM_MODEL_MNIST_8B_H\n#define SVM_MODEL_MNIST_8B_H\n\n")
    f.write("#include <stdint.h>\n\n")
    f.write(f"#define NUM_CLASSES {weights.shape[0]}\n")
    f.write(f"#ifndef NUM_FEATURES\n#define NUM_FEATURES {weights.shape[1]}\n#endif\n\n")

    f.write("/* real_weight = weights[c][i] * weight_scale */\n")
    f.write(f"static const float weight_scale = {weight_scale:.10e}f;\n\n")

    f.write("static const int8_t weights[NUM_CLASSES][NUM_FEATURES] = {\n")
    for row in weights_int8:
        f.write("    {" + ", ".join(str(v) for v in row) + "},\n")
    f.write("};\n\n")

    f.write("static const float bias[NUM_CLASSES] = {"
            + ", ".join(f"{b:.10f}f" for b in biases) + "};\n\n")
    f.write("#endif /* SVM_MODEL_MNIST_8B_H */\n")

print("Exported SVM model to svm_model_mnist_8b.h")

# --- Export StandardScaler parameters --------------------------------------
# The previous version quantized mean_ and scale_ to int8 with a factor that
# was never exported, so the C side could not recover the real values (and
# small std values rounded to 0 -> divide by zero). They are now exported as
# float, and the scale is stored as its reciprocal so the MCU multiplies
# instead of divides: x_scaled = (pixel - mean[i]) * inv_scale[i]
# (sklearn already sets scale_ = 1 for zero-variance pixels, so 1/scale_ is safe.)
def c_float(v):
    """Format a number as a valid C float literal (e.g. 0 -> 0.0f, 3 -> 3.0f)."""
    s = f"{float(v):.7g}"
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"

mean = scaler.mean_.astype(np.float32)
inv_scale = (1.0 / scaler.scale_).astype(np.float32)
with open("scaler_mnist_8b.h", "w") as f:
    f.write("#ifndef SCALER_MNIST_8B_H\n#define SCALER_MNIST_8B_H\n\n")
    f.write("#include <stdint.h>\n\n")
    f.write(f"#ifndef NUM_FEATURES\n#define NUM_FEATURES {len(mean)}\n#endif\n\n")

    f.write("static const float mean[NUM_FEATURES] = {\n")
    f.write("    " + ", ".join(c_float(m) for m in mean) + "\n};\n\n")

    f.write("static const float inv_scale[NUM_FEATURES] = {\n")
    f.write("    " + ", ".join(c_float(s) for s in inv_scale) + "\n};\n\n")
    f.write("#endif /* SCALER_MNIST_8B_H */\n")

print("Exported scaler parameters to scaler_mnist_8b.h")

NUM_IMAGES_TO_EXPORT = 10

assert X_test.shape[1] == 784
X_sample = X_test[:NUM_IMAGES_TO_EXPORT]
y_sample = y_test[:NUM_IMAGES_TO_EXPORT]

def export_test_images_to_c(images, labels, filename="mnist_images_8b.h"):
    num_images, num_features = images.shape
    # MNIST pixels are 0..255 -> uint8_t. (int8_t wrapped values >127 to negatives.)
    images_u8 = np.clip(images, 0, 255).astype(np.uint8)

    with open(filename, "w") as f:
        f.write("#ifndef TEST_IMAGES_H\n#define TEST_IMAGES_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define NUM_TEST_IMAGES {num_images}\n")
        f.write(f"#ifndef NUM_FEATURES\n#define NUM_FEATURES {num_features}\n#endif\n\n")

        # const -> stored in flash, not copied into RAM
        f.write("static const uint8_t test_images[NUM_TEST_IMAGES][NUM_FEATURES] = {\n")
        for img in images_u8:
            f.write("    {" + ", ".join(str(px) for px in img) + "},\n")
        f.write("};\n\n")

        f.write("static const uint8_t test_labels[NUM_TEST_IMAGES] = { ")
        f.write(", ".join(str(int(label)) for label in labels))
        f.write(" };\n\n")

        f.write("#endif // TEST_IMAGES_H\n")

    print(f"Generated {filename}")

export_test_images_to_c(X_sample, y_sample, "mnist_images_8b.h")

